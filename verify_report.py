"""
verify_report.py -- turns raw_clean.csv / raw_sweep.csv into results_verify/verify_summary.md using ONLY the
metrics and pass criteria written in VERIFICATION_PLAN.md. Nothing is tuned here.

    python verify_report.py
"""
import numpy as np, pandas as pd
import verify_common as V
import verify_stats as S
import fixed_cusum as F

D = 'D  Adaptive, all guardrails'
ABL = {'D- no pause': 'guardrail 1: pause learning', 'D- fast learning': 'guardrail 2: learn slowly',
       'D- no bounds': 'guardrail 3: physical bounds', 'D- no frozen copy': 'guardrail 4: frozen reference copy',
       'D- no hold test': 'guardrail 5: 24 h hold test'}
P1_PASS_UB, P1_POINT = 0.80, 0.63
P2_MISSED = 0.20
ORDER = ['PASS', 'MARGINAL', 'FAIL']


def md(df):
    cols = list(df.columns)
    out = ['| ' + ' | '.join(cols) + ' |', '|' + '|'.join('---' for _ in cols) + '|']
    for _, r in df.iterrows():
        out.append('| ' + ' | '.join(str(r[c]) for c in cols) + ' |')
    return '\n'.join(out)


def ci(t, f='%.2f'):
    return (f + ' [' + f + ', ' + f + ']') % tuple(t)


def p1(k, n):
    p, lo, hi = S.wilson(k, n)
    cat = 'PASS' if hi <= P1_PASS_UB else ('MARGINAL' if p <= P1_POINT else 'FAIL')
    return p, lo, hi, cat


def parse(s):
    if not isinstance(s, str) or not s:
        return []
    return [(float(x.split(':')[0]), x.split(':')[1]) for x in s.split(';')]


def main():
    cl = pd.read_csv(V.OUT + '/raw_clean.csv', keep_default_na=False)
    sw = pd.read_csv(V.OUT + '/raw_sweep.csv', keep_default_na=False)
    names = list(dict.fromkeys(cl['name']))
    L = ['# Verification results', '',
         'Generated by `verify_report.py` from frozen thresholds (`thresholds.json`). Criteria: `VERIFICATION_PLAN.md` section 4.',
         'Clean runs: %d (seeds %d-%d). Sweep: %d tubes x %d growth rates + leak-free twins.' % (
             cl['seed'].nunique(), V.CLEAN_SEEDS[0], V.CLEAN_SEEDS[-1], len(V.SWEEP_SEEDS), len(V.CREEP_DAYS)), '']

    # ---------------- M1 clean false alarms
    rows, win, p1cat = [], {}, {}
    for nm in names:
        d = cl[cl['name'] == nm].sort_values('seed')
        ind = (d['n_win'] > 0).astype(float).values
        win[nm] = ind
        p, lo, hi, cat = p1(int(ind.sum()), len(ind))
        p1cat[nm] = cat
        g = S.garwood_rate(int(d['n_total'].sum()), float(d['days_eval'].sum()))
        b = S.ratio_boot_ci(d['n_total'].values, d['days_eval'].values)
        rows.append({'detector': nm, 'runs with >=1 alarm, days 10-40 (Wilson 95%)': ci((p, lo, hi)),
                     'alarms per 30 d': '%.2f' % g[0], 'Garwood 95%': '[%.2f, %.2f]' % g[1:],
                     'run-bootstrap 95%': '[%.2f, %.2f]' % b[1:],
                     'frozen / verify / cusum alarms': '%d / %d / %d' % (d['n_frozen'].sum(), d['n_verify'].sum(), d['n_cusum'].sum()),
                     'P1': cat})
    L += ['## M1. False alarms on clean test runs (tuning target: 1 per 30 d)', '', md(pd.DataFrame(rows)), '',
          'P1: PASS if Wilson upper bound <= %.2f; MARGINAL if point <= %.2f but the upper bound is higher; FAIL otherwise.' % (P1_PASS_UB, P1_POINT), '']

    # ---------------- sweep: M2 / M3
    rate_of = {cd: V.LEAK_SIZE / cd for cd in V.CREEP_DAYS}
    start_h = V.LEAK_START_DAY * 24.0
    det_ind, srows = {}, []
    for nm in names:
        for cd in V.CREEP_DAYS:
            hz = (V.LEAK_START_DAY + cd + V.HORIZON_AFTER_FULL_DAYS) * 24.0
            lk = sw[(sw['name'] == nm) & (sw['creep_days'] == cd)].sort_values('seed')
            tw = sw[(sw['name'] == nm) & (sw['creep_days'] == -1)].sort_values('seed')
            det, dly, lvl = [], [], []
            for _, r in lk.iterrows():
                hit = [a for a, _ in parse(r['alarms']) if start_h < a <= hz]
                det.append(1.0 if hit else 0.0)
                if hit:
                    dly.append((hit[0] - start_h) / 24.0)
                    lvl.append(V.LEAK_SIZE * min((hit[0] - start_h) / (cd * 24.0), 1.0))
            ch = [1.0 if any(start_h < a <= hz for a, _ in parse(r['alarms'])) else 0.0 for _, r in tw.iterrows()]
            det_ind[(nm, cd)] = np.array(det)
            p, lo, hi = S.wilson(int(sum(det)), len(det))
            cp, clo, chi = S.wilson(int(sum(ch)), len(ch))
            ok = ((1 - p) <= P2_MISSED) and (lo > chi)
            srows.append({'detector': nm, 'growth Pa/h/day': '%.4f' % rate_of[cd], 'creep days': cd,
                          'detected (Wilson 95%)': ci((p, lo, hi)), 'missed share': '%.2f' % (1 - p),
                          'median delay, days (detected only)': ci(S.boot_ci(dly, np.median), '%.1f') if dly else 'none detected',
                          'median leak size at alarm, Pa/h': ('%.3f' % np.median(lvl)) if lvl else '-',
                          'chance (leak-free twin)': ci((cp, clo, chi)), 'P2': 'PASS' if ok else 'FAIL'})
    sdf = pd.DataFrame(srows)
    L += ['## M2/M3. Slow-leak sweep (final size %.2f Pa/h, %d tubes per cell)' % (V.LEAK_SIZE, len(V.SWEEP_SEEDS)), '',
          'Detected = an alarm within (creep days + 30) days of leak start. Missed = 1 - detected. '
          'Chance = share of leak-free twins with an alarm in the same window.', '']
    for nm in names:
        L += ['### ' + nm, '', md(sdf[sdf['detector'] == nm].drop(columns='detector')), '']

    # ---------------- P3 baseline comparison
    L += ['## P3. D versus the non-adaptive baselines (paired by tube; detected share, D minus baseline)', '']
    rows = []
    for base in (F.F0, F.F1):
        for cd in V.CREEP_DAYS:
            dd = S.paired_diff_ci(det_ind[(D, cd)], det_ind[(base, cd)])
            worse_fa = ORDER.index(p1cat[D]) > ORDER.index(p1cat[base])
            if dd[1] > 0:
                verdict = 'D better detection but worse P1' if worse_fa else 'D better'
            elif dd[2] < 0:
                verdict = 'baseline better'
            else:
                verdict = 'no difference shown'
            rows.append({'baseline': base, 'growth Pa/h/day': '%.4f' % rate_of[cd], 'diff in detected share': ci(dd), 'verdict': verdict})
    L += [md(pd.DataFrame(rows)), '']

    # ---------------- P4 guardrails
    L += ['## P4. Does each guardrail do anything? (ablation minus D, paired by tube)', '']
    rows = []
    dcl = cl[cl['name'] == D].sort_values('seed')
    for ab, gname in ABL.items():
        acl = cl[cl['name'] == ab].sort_values('seed')
        same = float(np.mean(acl['alarms'].values == dcl['alarms'].values))
        fa = S.paired_diff_ci(win[ab], win[D])
        dets = [S.paired_diff_ci(det_ind[(ab, cd)], det_ind[(D, cd)]) for cd in V.CREEP_DAYS]
        zero_fa = fa[1] <= 0 <= fa[2]
        zero_det = all(x[1] <= 0 <= x[2] for x in dets)
        harmful = (fa[2] < 0) and all(x[1] > 0 for x in dets)
        verdict = 'INERT (no measurable effect)' if zero_fa and zero_det else 'HARMFUL' if harmful else 'has an effect'
        rows.append({'removed': gname, 'ablation': ab, 'clean runs with identical alarm list': '%.0f%%' % (100 * same),
                     'clean window fraction, ablation - D': ci(fa, '%.3f'),
                     'detected share, ablation - D (growth fastest -> slowest)': '; '.join('%+.2f' % x[0] for x in dets),
                     'verdict': verdict})
    L += [md(pd.DataFrame(rows)), '',
          'Verdict rule (plan, P4): INERT if every paired 95% interval includes 0; HARMFUL if removal lowers clean false alarms '
          'and raises detection at every rate with intervals excluding 0; otherwise "has an effect" (direction is in the columns).', '']

    L += ['## Reading these numbers', '',
          '- The sweep has %d tubes per cell, so cell-level intervals are wide; differences inside them are not evidence.' % len(V.SWEEP_SEEDS),
          '- Detector and simulator share equations; this does not show performance on a real tube.', '']
    open(V.OUT + '/verify_summary.md', 'w').write('\n'.join(L))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
